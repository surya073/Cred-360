const RECENT_KEY = 'keyshare_chat_recent_emojis';
const RECENT_MAX = 24;

export function loadRecentEmojis() {
  try {
    const v = JSON.parse(localStorage.getItem(RECENT_KEY) || '[]');
    return Array.isArray(v) ? v.slice(0, RECENT_MAX) : [];
  } catch (e) {
    return [];
  }
}

export function rememberEmoji(emoji) {
  try {
    const next = [emoji, ...loadRecentEmojis().filter(e => e !== emoji)].slice(0, RECENT_MAX);
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
    return next;
  } catch (e) {
    return [];
  }
}
